def get_niche(niche_key: str) -> Optional[NicheConfig]:
    return NICHES.get(niche_key)

def get_chat_id_for_niche(niche_key: str) -> str:
    """Возвращает Chat ID группы WhatsApp для конкретной ниши из окружения."""
    niche = get_niche(niche_key)
    default_id = os.getenv("WA_CHAT_DEFAULT", "").strip()
    if not niche:
        return default_id
    val = os.getenv(niche.env_chat_id_key, "").strip()
    return val if val else default_id
